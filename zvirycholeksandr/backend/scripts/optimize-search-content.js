  matched += 1;
  const isCurrent = Object.entries(update).every(([key, value]) => JSON.stringify(record[key]) === JSON.stringify(value));
  if (isCurrent) continue;
  Object.assign(record, update, { updatedAt: new Date().toISOString() });
