const filepath = path.join(dataDir, 'blog.json');
const records = JSON.parse(fs.readFileSync(filepath, 'utf8'));
if (!Array.isArray(records)) throw new Error('blog.json має містити масив');

let changed = 0;
for (const record of records) {
  const update = articles[record.slug];
  if (!update) continue;
  Object.assign(record, update, { updatedAt: new Date().toISOString() });
  changed += 1;
}

if (!changed) {
  console.error('Не знайдено жодної цільової статті');
  process.exit(1);
}

const temporary = `${filepath}.tmp`;
fs.writeFileSync(temporary, `${JSON.stringify(records, null, 2)}\n`, { mode: 0o600 });
fs.chmodSync(temporary, 0o600);
fs.renameSync(temporary, filepath);
console.log(`Оновлено SEO-контент для ${changed} статей`);
